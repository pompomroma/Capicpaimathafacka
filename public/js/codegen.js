import * as api from './api.js';

const form = document.getElementById('codegen-form');
const goalEl = document.getElementById('codegen-goal');
const runBtn = document.getElementById('codegen-run');
const previewBtn = document.getElementById('codegen-preview');
const downloadBtn = document.getElementById('codegen-download');
const statusEl = document.getElementById('codegen-status');
const filesEl = document.getElementById('codegen-files');
const iframe = document.getElementById('codegen-iframe');

let current = null; // { files, entry, goal, notes }

function setStatus(s) { statusEl.textContent = s || ''; }

function pickFile(path) { return current?.files.find(f => f.path === path); }

function buildPreviewDoc() {
  if (!current) return null;
  const entry = pickFile(current.entry);
  if (!entry) return null;

  // For html entry: inline referenced CSS/JS from project files using <base> rewriting.
  const cssFiles = current.files.filter(f => /\.css$/i.test(f.path));
  const jsFiles = current.files.filter(f => /\.js$/i.test(f.path));

  let html = entry.content;
  // Replace local <link rel="stylesheet" href="X"> and <script src="X"> with inline tags
  for (const f of cssFiles) {
    const rx = new RegExp(`<link[^>]*href=["']${f.path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}["'][^>]*>`, 'g');
    html = html.replace(rx, `<style>${f.content}</style>`);
  }
  for (const f of jsFiles) {
    const rx = new RegExp(`<script[^>]*src=["']${f.path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}["'][^>]*></script>`, 'g');
    html = html.replace(rx, `<script>${f.content}</script>`);
  }
  return html;
}

function renderFileList() {
  if (!current) { filesEl.textContent = ''; return; }
  filesEl.innerHTML = current.files.map(f => `<div>· ${f.path} <span style="opacity:.6">(${f.content.length} bytes)</span></div>`).join('');
}

export function loadCreation(rec) {
  current = { files: rec.files, entry: rec.entry, goal: rec.goal, notes: rec.notes };
  goalEl.value = rec.goal || '';
  renderFileList();
  setStatus(`Loaded creation: ${rec.files.length} files`);
}

form.addEventListener('submit', async (e) => {
  e.preventDefault();
  const goal = goalEl.value.trim();
  if (!goal) return;
  runBtn.disabled = true;
  setStatus('Generating… complex projects may take 30–60 s.');
  try {
    const res = await api.codegen(goal);
    current = { ...res, goal };
    const parts = [`Built ${res.files.length} files`];
    if (res.stack) parts.push(`in ${res.stack}`);
    parts.push(`. Entry: ${res.entry}.`);
    if (res.run) parts.push(` Run: ${res.run}.`);
    if (res.notes) parts.push(` — ${res.notes}`);
    setStatus(parts.join(''));
    renderFileList();
  } catch (err) {
    // api.js throws `Error(json.error)` from /api/codegen — and the
    // server now includes a `raw` model-output snippet on 502 errors
    // so the user can see what was actually emitted.
    let msg = err?.message || String(err);
    // Friendlier hints for the common failure modes.
    if (/NIM_KEY_CODEGEN not set/i.test(msg)) {
      msg = 'NVIDIA NIM codegen key not configured. Add NIM_KEY_CODEGEN to your Replit Secrets (or .env) and click Run again.';
    } else if (/no parseable files/i.test(msg)) {
      msg = 'Model did not return parseable file blocks. Try a more specific goal (e.g. "build me a snake game in vanilla HTML"). ' + msg;
    }
    setStatus('Error: ' + msg);
  } finally {
    runBtn.disabled = false;
  }
});

previewBtn.addEventListener('click', () => {
  const doc = buildPreviewDoc();
  if (!doc) { setStatus('Nothing to preview yet.'); return; }
  iframe.hidden = false;
  iframe.srcdoc = doc;
});

downloadBtn.addEventListener('click', async () => {
  if (!current) { setStatus('Nothing to download yet.'); return; }
  const zip = new JSZip();
  for (const f of current.files) zip.file(f.path, f.content);
  // Add a tiny manifest
  zip.file('FRIDAY_README.txt', `Generated by Friday\nGoal: ${current.goal}\nEntry: ${current.entry}\n${current.notes || ''}\n`);
  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  const safe = (current.goal || 'friday-creation').toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40);
  a.href = url; a.download = `${safe || 'creation'}.zip`;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
});
